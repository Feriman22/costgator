def po_escape(text):
    return text.replace("\\", "\\\\").replace('"', '\\"')


def main():
    pot = (ROOT / "costgator.pot").read_text()
    pot_ids = set(re.findall(r'^msgid "(.+)"$', pot, re.M))
    missing = [k for k in KEYS if k not in pot_ids]
    if missing:
        sys.exit("Keys not in POT: %r" % missing)

    for locale, values in T.items():
        if len(values) != len(KEYS):
            sys.exit("%s has %d strings, expected %d" % (locale, len(values), len(KEYS)))
        for key, value in zip(KEYS, values):
            if re.findall(r"%(?:\d\$)?s", key) != re.findall(r"%(?:\d\$)?s", value):
                sys.exit("%s placeholder mismatch: %r" % (locale, key))
        out = [
            'msgid ""',
            'msgstr ""',
            '"Project-Id-Version: CostGator Margin Audit for WooCommerce 0.1.0\\n"',
            '"Language: %s\\n"' % locale,
            '"MIME-Version: 1.0\\n"',
            '"Content-Type: text/plain; charset=UTF-8\\n"',
            '"Content-Transfer-Encoding: 8bit\\n"',
            '"Plural-Forms: nplurals=2; plural=(n != 1);\\n"',
            '"X-Domain: costgator\\n"',
            "",
        ]
        for key, value in zip(KEYS, values):
            out += ['msgid "%s"' % po_escape(key), 'msgstr "%s"' % po_escape(value), ""]
        (ROOT / ("costgator-%s.po" % locale)).write_text("\n".join(out))
        print("wrote", locale)


main()
